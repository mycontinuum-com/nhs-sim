import { writeFileSync } from "node:fs";
import { seedWorld } from "../packages/engine/src/index.ts";
const COUNT = Number(process.argv[3] ?? 50), SEED = Number(process.argv[4] ?? 42);
const w = seedWorld("take-home", SEED, COUNT) as any;
const iso = (v: any): any => {
  if (Array.isArray(v)) return v.map(iso);
  if (v && typeof v === "object")
    return Object.fromEntries(Object.entries(v).map(([k, x]) =>
      [k, /At$/.test(k) && typeof x === "number" ? new Date(x).toISOString() : iso(x)]));
  return v;
};
const strip = (r: any) => iso({
  id: r.id, kind: r.kind, title: r.title, status: r.status, owner: r.owner,
  priority: r.priority, createdAt: r.createdAt, dueAt: r.dueAt,
  ...(r.data && Object.keys(r.data).length ? { data: r.data } : {}),
});
const byPatient = new Map<string, any[]>();
for (const r of w.resources) if (r.patientId) (byPatient.get(r.patientId) ?? byPatient.set(r.patientId, []).get(r.patientId)!).push(r);
const drop = new Set(["genome-record", "provider-metric", "theatre-slot", "bed"]);
const patients = w.patients.map((p: any) => {
  const rs = (byPatient.get(p.id) ?? []).filter(r => !drop.has(r.kind));
  const ehr = rs.find(r => r.kind === "ehr-record")?.data ?? {};
  const labs = rs.filter(r => r.kind === "report" && r.data?.kind === "blood-result").map(r => iso({
    id: r.id, panel: r.data.panel.name, collectedAt: r.data.collectedAt, laboratory: r.data.laboratory,
    results: r.data.analytes.map((a: any) => ({ test: a.name, value: a.value, unit: a.unit, referenceLow: a.referenceLow, referenceHigh: a.referenceHigh })),
  }));
  const pick = (k: string) => rs.filter(r => r.kind === k).map(strip);
  const used = new Set(["ehr-record", "encounter", "appointment", "observation", "discharge-summary"]);
  return {
    id: p.id, name: p.name, birthDate: p.birthDate, localIdentifiers: p.localIds,
    conditions: p.conditions, accessNeeds: p.needs, goals: p.goals,
    problems: ehr.problems ?? [], medications: ehr.medications ?? [], allergies: ehr.allergies ?? [],
    labResults: labs,
    observations: pick("observation"),
    encounters: pick("encounter"),
    appointments: pick("appointment"),
    dischargeSummaries: pick("discharge-summary"),
    otherRecords: rs.filter(r => !used.has(r.kind) && !(r.kind === "report" && r.data?.kind === "blood-result")).map(strip),
  };
});
const out = {
  meta: {
    description: "Entirely synthetic patient dataset generated by the nhs-sim simulation engine. Fictional people, values and dates. Not real patient data; not clinical guidance.",
    generator: "nhs-sim seedWorld", seed: SEED, generatedForSimulationTime: new Date(w.now).toISOString(), patientCount: patients.length,
  },
  patients,
};
writeFileSync(process.argv[2] ?? "output/take-home-patients.json", JSON.stringify(out, null, 2));
// Usage: node --experimental-strip-types scripts/export-take-home-patients.ts <out.json> [count] [seed]
